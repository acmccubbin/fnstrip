#!/usr/bin/env python3
"""Regenerates docs/media and the web page's icon sprites (docs/site): renders frames with the real drawing code and made-up data (see
src/demo_media.rs), then builds the pictures. The bar is 36 times wider than tall, so the
animations show it folded onto two lines, which stays readable at web-page width.

Run from the project root: python3 tools/make_demo_media.py  (needs Pillow, NumPy and ffmpeg)
"""
import base64
import io
import json
import os
import re
import subprocess
import tempfile

import numpy as np
from PIL import Image, ImageDraw, ImageFont

WIDTH, HEIGHT = 2170, 60
FOLD = 1002  # between plates on every row
SCALE = 0.75
MARGIN, GAP, CAPTION = 14, 10, 34
FPS = 15
OUT = "docs/media"
FONT = ImageFont.truetype("/usr/share/fonts/Adwaita/AdwaitaSans-Regular.ttf", 18)


SITE = "docs/site"
# Plate x and width on each sprite row (see render_sprite_rows), and the label/icon colour.
SLIDER_ICON = 72
EXTRA_PLATES = [194, 384, 574, 848, 1038, 1228, 1418, 1608, 1798, 1988]
FUNCTION_PLATES = [172 + 167 * i for i in range(12)]
LABEL = 242


def cut(frame, name, x, width, background, sprites, sheet):
    """One icon as white with alpha, cropped to its pixels; its offset is from the plate."""
    part = frame[:, x:x + width].astype(float)
    channel = int(np.argmin(background))
    alpha = (part[:, :, channel] - background[channel]) / (LABEL - background[channel])
    alpha = np.clip(alpha, 0, 1)
    rows, cols = np.nonzero(alpha > 0.02)
    top, bottom, left, right = rows.min(), rows.max() + 1, cols.min(), cols.max() + 1
    mask = (alpha[top:bottom, left:right] * 255).round().astype(np.uint8)
    sheet.append(mask)
    sprites[name] = {"dx": int(left), "dy": int(top), "w": int(right - left), "h": int(bottom - top)}


def sprite_sheet(rows, wordmark):
    """docs/site/sprites.js: the icons, white on transparent in one row, and their places."""
    grey, green = (53, 53, 53), (32, 128, 64)
    controls, muted, function, extras_off, extras_on = rows
    sprites, sheet = {}, []
    cut(controls, "esc", 0, 162, grey, sprites, sheet)
    cut(controls, "brightness", 194, SLIDER_ICON, grey, sprites, sheet)
    cut(controls, "keyboard", 602, SLIDER_ICON, grey, sprites, sheet)
    for name, x in [("previous", 1010), ("playpause", 1200), ("next", 1390)]:
        cut(controls, name, x, 182, grey, sprites, sheet)
    cut(controls, "volume", 1608, SLIDER_ICON, grey, sprites, sheet)
    cut(muted, "muted", 1608, SLIDER_ICON, grey, sprites, sheet)
    for index, x in enumerate(FUNCTION_PLATES):
        cut(function, f"F{index + 1}", x, 157, grey, sprites, sheet)
    names = ["camera", "mic", "vpn", "cpu", "temp", "fan", "mem", "disk", "net", "battery"]
    for name, x in zip(names, EXTRA_PLATES):
        cut(extras_off, name, x, 182, grey, sprites, sheet)
    for name, x in zip(["camera-on", "mic-on", "vpn-on"], EXTRA_PLATES):
        cut(extras_on, name, x, 182, green, sprites, sheet)
    cut(extras_on, "battery-on", EXTRA_PLATES[9], 182, green, sprites, sheet)
    sheet.append(wordmark)
    sprites["wordmark"] = {"dx": 0, "dy": 0, "w": wordmark.shape[1], "h": wordmark.shape[0]}
    width = sum(mask.shape[1] + 2 for mask in sheet)
    image = np.zeros((max(mask.shape[0] for mask in sheet), width, 4), dtype=np.uint8)
    x = 0
    for (name, place), mask in zip(sprites.items(), sheet):
        image[:mask.shape[0], x:x + mask.shape[1], :3] = 255
        image[:mask.shape[0], x:x + mask.shape[1], 3] = mask
        place["x"] = x
        x += mask.shape[1] + 2
    os.makedirs(SITE, exist_ok=True)
    png = io.BytesIO()
    Image.fromarray(image, "RGBA").save(png, "PNG", optimize=True)
    # Inline as a data URL: an image file would taint the canvas when the page is opened
    # straight from disk (file://), and the startup animation reads the canvas back.
    sheet_url = "data:image/png;base64," + base64.b64encode(png.getvalue()).decode()
    with open(os.path.join(SITE, "sprites.js"), "w") as out:
        out.write("// Generated by tools/make_demo_media.py from the renderer's own drawing; do not edit.\n")
        out.write("// The icon sheet (white on transparent) and each icon's place in it (x, w, h) and\n")
        out.write("// in its plate (dx, dy).\n")
        out.write(f"window.SPRITES = {json.dumps(sprites, separators=(',', ':'))};\n")
        out.write(f"window.SPRITE_SHEET = '{sheet_url}';\n")


def wordmark():
    """The startup animation's wordmark mask, from src/wordmark.rs."""
    text = open("src/wordmark.rs").read()
    width = int(re.search(r"width: (\d+)", text).group(1))
    height = int(re.search(r"height: (\d+)", text).group(1))
    pixels = re.search(r"pixels: &\[(.*?)\]", text, re.S).group(1)
    values = [int(value) for value in re.findall(r"\d+", pixels)]
    return np.array(values, dtype=np.uint8).reshape(height, width)


def frames(directory, name):
    raw = np.fromfile(os.path.join(directory, f"{name}.raw"), dtype=np.uint8)
    return raw.reshape(-1, HEIGHT, WIDTH, 4)[:, :, :, [2, 1, 0]]  # BGRX to RGB


def finger(frame, x):
    """A translucent fingertip, in native bar pixels."""
    image = Image.fromarray(frame).convert("RGBA")
    layer = Image.new("RGBA", image.size)
    ImageDraw.Draw(layer).ellipse((x - 22, 8, x + 22, 52), fill=(255, 90, 80, 150))
    return np.asarray(Image.alpha_composite(image, layer).convert("RGB"))


def fold(frame, caption=""):
    """The bar on two lines, with an optional caption above, on a dark background."""
    left = Image.fromarray(frame[:, :FOLD])
    right = Image.fromarray(frame[:, FOLD:])
    size = lambda part: (round(part.width * SCALE), round(part.height * SCALE))
    left, right = left.resize(size(left), Image.LANCZOS), right.resize(size(right), Image.LANCZOS)
    top = MARGIN + (CAPTION if caption else 0)
    canvas = Image.new("RGB", (right.width + 2 * MARGIN, top + 2 * left.height + GAP + MARGIN), (24, 24, 24))
    canvas.paste(left, (MARGIN, top))
    canvas.paste(right, (MARGIN, top + left.height + GAP))
    if caption:
        ImageDraw.Draw(canvas).text((MARGIN, MARGIN), caption, font=FONT, fill=(235, 235, 235))
    return canvas


def strip(frame, caption, left, right, scale):
    """Part of the bar on one line (unfolded), with a caption above."""
    part = Image.fromarray(frame[:, left:right])
    part = part.resize((round(part.width * scale), round(part.height * scale)), Image.LANCZOS)
    canvas = Image.new("RGB", (part.width + 2 * MARGIN, MARGIN + CAPTION + part.height + MARGIN), (24, 24, 24))
    canvas.paste(part, (MARGIN, MARGIN + CAPTION))
    ImageDraw.Draw(canvas).text((MARGIN, MARGIN), caption, font=FONT, fill=(235, 235, 235))
    return canvas


def video(name, images, fps=FPS):
    """Writes a silent MP4 (H.264, 4:2:0, so every browser plays it, iPhone Safari included);
    about a tenth of the size of the same GIF. For the web page; the README keeps GIFs."""
    width, height = images[0].size
    width -= width % 2
    height -= height % 2
    command = ["ffmpeg", "-loglevel", "error", "-y", "-f", "rawvideo", "-pix_fmt", "rgb24",
               "-s", f"{width}x{height}", "-r", str(fps), "-i", "-", "-an", "-c:v", "libx264",
               "-preset", "slow", "-crf", "18", "-pix_fmt", "yuv420p", "-movflags", "+faststart",
               os.path.join(OUT, f"{name}.mp4")]
    ffmpeg = subprocess.Popen(command, stdin=subprocess.PIPE)
    for image in images:
        ffmpeg.stdin.write(image.crop((0, 0, width, height)).convert("RGB").tobytes())
    ffmpeg.stdin.close()
    ffmpeg.wait()


def gradient_text(text, font, colors):
    """`text` filled with a left-to-right gradient through `colors`, as an RGBA image."""
    left, top, right, bottom = font.getbbox(text)
    mask = Image.new("L", (right, bottom))
    ImageDraw.Draw(mask).text((0, 0), text, font=font, fill=255)
    width = right
    ramp = Image.new("RGB", (width, 1))
    for x in range(width):
        t = x / max(1, width - 1) * (len(colors) - 1)
        i = min(int(t), len(colors) - 2)
        f = t - i
        ramp.putpixel((x, 0), tuple(round(a + (b - a) * f) for a, b in zip(colors[i], colors[i + 1])))
    image = ramp.resize((width, bottom)).convert("RGBA")
    image.putalpha(mask)
    return image


def bold(size):
    face = ImageFont.truetype("/usr/share/fonts/Adwaita/AdwaitaSans-Regular.ttf", size)
    face.set_variation_by_name("Bold")
    return face


def share_image(controls, extras):
    """docs/media/og.png: the 1200x630 picture shown when the page is shared."""
    canvas = Image.new("RGB", (1200, 630), (10, 10, 12))
    draw = ImageDraw.Draw(canvas)
    brand = gradient_text("fnstrip", bold(104), [(0, 199, 255), (124, 140, 255), (255, 61, 199)])
    canvas.paste(brand, (56, 44), brand)
    draw.text((60, 186), "Your Touch Bar, your buttons.", font=bold(46), fill=(236, 236, 240))
    regular = ImageFont.truetype("/usr/share/fonts/Adwaita/AdwaitaSans-Regular.ttf", 26)
    draw.text((62, 252), "For 2016-2017 MacBook Pros on Linux, with T1Bridge. Free and open source.",
              font=regular, fill=(155, 155, 166))
    # The bar, folded in two lines per row, scaled so the wider half fits 1080 px.
    # The extras row folds at its own gap, between the CPU and temperature meters.
    folds = ((controls, FOLD), (extras, 1034))
    scale = 1080 / max(frame.shape[1] - fold for frame, fold in folds)
    top = 324
    for frame, fold in folds:
        for half in (frame[:, :fold], frame[:, fold:]):
            row = Image.fromarray(half)
            row = row.resize((round(row.width * scale), round(row.height * scale)), Image.LANCZOS)
            canvas.paste(row, (60, top))
            top += row.height + 8
        top += 8
    canvas.save(os.path.join(OUT, "og.png"))


def touch_icon():
    """docs/site/icon-180.png: the home-screen icon (iPhone), "fn" on the page's dark."""
    size = 180
    icon = Image.new("RGB", (size, size), (10, 10, 12))
    text = gradient_text("fn", bold(112), [(0, 199, 255), (255, 61, 199)])
    left, top, right, bottom = text.getbbox()
    icon.paste(text, ((size - (right - left)) // 2 - left, (size - (bottom - top)) // 2 - top), text)
    icon.save(os.path.join(os.path.dirname(OUT), "site", "icon-180.png"))


def gif(name, images, fps=FPS, colors=96):
    """Writes a looping GIF with one shared palette."""
    width, height = images[0].size
    width -= width % 2
    height -= height % 2
    command = ["ffmpeg", "-loglevel", "error", "-y", "-f", "rawvideo", "-pix_fmt", "rgb24",
               "-s", f"{width}x{height}", "-r", str(fps), "-i", "-", "-filter_complex",
               f"split[a][b];[a]palettegen=max_colors={colors}:stats_mode=diff[p];"
               "[b][p]paletteuse=dither=none:diff_mode=rectangle",
               "-loop", "0", os.path.join(OUT, f"{name}.gif")]
    ffmpeg = subprocess.Popen(command, stdin=subprocess.PIPE)
    for image in images:
        ffmpeg.stdin.write(image.crop((0, 0, width, height)).tobytes())
    ffmpeg.stdin.close()
    ffmpeg.wait()


def main():
    os.makedirs(OUT, exist_ok=True)
    with tempfile.TemporaryDirectory() as directory:
        subprocess.run(
            ["cargo", "test", "--release", "--lib", "render_demo_frames", "--", "--ignored"],
            check=True, stdout=subprocess.DEVNULL,
            env={**os.environ, "FNSTRIP_DEMO_DIR": directory, "XDG_STATE_HOME": directory},
        )
        controls = frames(directory, "controls")[0]
        function = frames(directory, "function")[0]
        extras = frames(directory, "extras")
        sliders = frames(directory, "sliders")
        test_screen = frames(directory, "test-screen")
        intro = frames(directory, "intro")
        sprite_rows = frames(directory, "sprites")
        themes = frames(directory, "themes")
        with open(os.path.join(directory, "sliders.txt")) as text:
            fingers = [line.strip() for line in text]

    sprite_sheet(sprite_rows, wordmark())

    # Full-width stills.
    Image.fromarray(controls).save(os.path.join(OUT, "controls.png"))
    Image.fromarray(function).save(os.path.join(OUT, "function.png"))
    Image.fromarray(extras[60]).save(os.path.join(OUT, "extras.png"))

    # Every built-in theme (src/theme.rs, Theme::NAMES order): its controls and extras rows.
    names = ["default", "pastel", "mono", "rainbow"]
    assert len(themes) == 2 * len(names)
    panels = [fold(themes[2 * index + row], f'theme = "{name}"' if row == 0 else "")
              for index, name in enumerate(names) for row in (0, 1)]
    sheet = Image.new("RGB", (panels[0].width, sum(panel.height for panel in panels)))
    top = 0
    for panel in panels:
        sheet.paste(panel, (0, top))
        top += panel.height
    sheet.save(os.path.join(OUT, "themes.png"))

    # The three rows, as Fn changes them.
    rows = [(controls, "Normally: Esc, sliders and media"),
            (function, "While Fn is held: Esc and F1-F12"),
            (extras[60], "After a double-tap of Fn: your buttons and live meters")]
    gif("rows", [fold(frame, caption) for frame, caption in rows for _ in range(2)], fps=1 / 1.25)

    images = []
    for frame, x in zip(sliders, fingers):
        images.append(fold(frame if x == "-" else finger(frame, int(x)), "Drag anywhere on a slider; tap the speaker to mute"))
    gif("sliders", images)
    gif("extras", [fold(frame, "Toggles, then CPU, temperature, fans, memory, disk, network, battery (sample data)") for frame in extras])
    # Unfolded, so the flash and the wordmark stay whole: the middle 1240 px of the bar.
    gif("intro", [strip(frame, "Starting up (startup_animation = \"off\" skips it)", 465, 1705, 0.73)
                  for frame in intro], fps=30, colors=256)
    gif("test-screen", [fold(frame, "The test screen: triple-tap Fn and hold") for frame in test_screen])

    # The web page's versions: the whole bar on one line at its own size, no caption (the
    # page captions them), so every picture looks like the real bar.
    os.makedirs(os.path.join(OUT, "strip"), exist_ok=True)
    native = Image.fromarray
    # Videos, not GIFs: about a tenth of the size. The rows one holds each row 1.25 s at 4 fps.
    video("strip/rows", [native(frame) for frame in (controls, function, extras[60]) for _ in range(5)], fps=4)
    video("strip/sliders", [native(frame if x == "-" else finger(frame, int(x))) for frame, x in zip(sliders, fingers)])
    video("strip/extras", [native(frame) for frame in extras])
    video("strip/intro", [native(frame) for frame in intro], fps=30)
    video("strip/test-screen", [native(frame) for frame in test_screen])
    for old in ("rows", "sliders", "extras", "intro", "test-screen"):
        path = os.path.join(OUT, "strip", f"{old}.gif")
        if os.path.exists(path):
            os.remove(path)
    share_image(controls, extras[60])
    touch_icon()
    for name in sorted(os.listdir(OUT)) + [f"strip/{name}" for name in sorted(os.listdir(os.path.join(OUT, "strip")))]:
        path = os.path.join(OUT, name)
        if os.path.isfile(path):
            print(f"{name}: {os.path.getsize(path) // 1024} KiB")


main()
