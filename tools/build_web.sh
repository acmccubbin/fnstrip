#!/usr/bin/env bash
# Builds web/ (fnstrip's own drawing code for the browser) and embeds it in
# docs/site/fnstrip-wasm.js, so the project page draws its bar with the renderer's code.
# Needs the wasm32-unknown-unknown Rust target (Arch: rust-wasm; rustup: rustup target add).
# Run from the project root: tools/build_web.sh
set -euo pipefail
cd "$(dirname "$0")/.."
(cd web && cargo build --release --locked --target wasm32-unknown-unknown)
target=$(cd web && cargo metadata --format-version 1 --no-deps | python3 -c 'import json,sys; print(json.load(sys.stdin)["target_directory"])')
wasm="$target/wasm32-unknown-unknown/release/fnstrip_web.wasm"
{
  echo "// Generated by tools/build_web.sh from web/ (fnstrip's own drawing code); do not edit."
  printf 'window.FNSTRIP_WASM = "%s";\n' "$(base64 -w0 "$wasm")"
} > docs/site/fnstrip-wasm.js
echo "docs/site/fnstrip-wasm.js: $(( $(stat -c %s docs/site/fnstrip-wasm.js) / 1024 )) KiB (wasm $(( $(stat -c %s "$wasm") / 1024 )) KiB)"
