#!/usr/bin/env python3
"""Generates src/wordmark.rs: the "fnstrip" wordmark the startup animation shows, as one
alpha mask, from Adwaita Sans Bold (SIL OFL 1.1; derived from Inter, like the stock labels).

Run from the project root: python3 tools/wordmark.py > src/wordmark.rs
"""
from PIL import Image, ImageDraw, ImageFont

FONT = "/usr/share/fonts/Adwaita/AdwaitaSans-Regular.ttf"
TEXT = "fnstrip"
SIZE = 44  # pixel size; "f" to "p" is ~43 px, on a 60 px bar


def main():
    face = ImageFont.truetype(FONT, SIZE)
    face.set_variation_by_name("Bold")
    left, top, right, bottom = face.getbbox(TEXT)
    image = Image.new("L", (right - left + 2, bottom - top + 2))
    ImageDraw.Draw(image).text((1 - left, 1 - top), TEXT, font=face, fill=255)
    pixels = image.tobytes()
    print("// Generated by tools/wordmark.py from Adwaita Sans Bold (SIL OFL 1.1);")
    print("// do not edit by hand.")
    print("use crate::stock_labels::AlphaMask;")
    print()
    print(f'/// "{TEXT}", {SIZE} px.')
    print("pub(crate) const WORDMARK: AlphaMask = AlphaMask {")
    print(f"    width: {image.width},")
    print(f"    height: {image.height},")
    print("    pixels: &[")
    row = []
    for value in pixels:
        row.append(f"{value},")
        if len(" ".join(row)) > 88:
            print("        " + " ".join(row[:-1]))
            row = row[-1:]
    if row:
        print("        " + " ".join(row))
    print("    ],")
    print("};")


main()
