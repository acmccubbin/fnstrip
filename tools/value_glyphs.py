#!/usr/bin/env python3
"""Generates src/value_glyphs.rs: alpha masks of the characters the meters print
("0-9 . % k M G B : ° C F"), in two sizes, from Adwaita Sans Medium (SIL OFL 1.1; derived from Inter,
like the stock labels). Digits get one shared advance so numbers don't jiggle.

Run from the project root: python3 tools/value_glyphs.py > src/value_glyphs.rs
"""
from PIL import Image, ImageDraw, ImageFont

FONT = "/usr/share/fonts/Adwaita/AdwaitaSans-Regular.ttf"
CHARS = "0123456789.%kMGB:°CF"
SIZES = {"LARGE": 24, "SMALL": 18}  # pixel sizes; cap height ~17 and ~13


def font(size):
    face = ImageFont.truetype(FONT, size)
    face.set_variation_by_name("Medium")
    return face


def render(size):
    face = font(size)
    ascent, descent = face.getmetrics()
    height = ascent + descent
    digit_advance = max(face.getlength(c) for c in "0123456789")
    glyphs = []
    for char in CHARS:
        advance = digit_advance if char.isdigit() else face.getlength(char)
        width = int(round(advance)) + 2
        image = Image.new("L", (width, height))
        offset = (advance - face.getlength(char)) / 2 + 1
        ImageDraw.Draw(image).text((offset, 0), char, font=face, fill=255)
        glyphs.append((char, image))
    # Crop every glyph to the rows any glyph uses, so they share a baseline.
    top = min(image.getbbox()[1] for _, image in glyphs)
    bottom = max(image.getbbox()[3] for _, image in glyphs)
    return [(char, image.crop((0, top, image.width, bottom))) for char, image in glyphs]


def main():
    print("// Generated by tools/value_glyphs.py from Adwaita Sans Medium (SIL OFL 1.1);")
    print("// do not edit by hand.")
    print("use crate::stock_labels::AlphaMask;")
    print()
    for name, size in SIZES.items():
        glyphs = render(size)
        print(f"/// Meter value glyphs, {size} px: (character, mask), the mask width is the advance.")
        print(f"pub(crate) const {name}: [(char, AlphaMask); {len(glyphs)}] = [")
        for char, image in glyphs:
            pixels = ", ".join(str(value) for value in image.tobytes())
            print(f"    ({char!r}, AlphaMask {{ width: {image.width}, height: {image.height}, "
                  f"pixels: &[{pixels}] }}),")
        print("];")
        print()


main()
